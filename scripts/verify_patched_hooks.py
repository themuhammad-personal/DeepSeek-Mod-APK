#!/usr/bin/env python3
"""Verify that the Morphe patches landed in the intended methods of a patched APK.

The MPP build only proves that the patch code compiles. This harness proves that the
generated bytecode actually calls the extension hooks from the intended DeepSeek
methods, which is the first thing that the previous branch never verified.

Checks performed on the patched APK:

  1. the DEX extension classes are present,
  2. the prompt serializer calls SdsAgentHooks.beforePrompt,
  3. the streaming ResponseFragment SET method calls SdsAgentHooks.observeResponse,
  4. the streaming ResponseFragment APPEND method calls SdsAgentHooks.observeResponse,
  5. the native Agent Console Activity is declared in the manifest,
  6. the original DeepSeek launcher Activity is still declared.

Usage:
    python3 scripts/verify_patched_hooks.py <patched.apk>
"""

from __future__ import annotations

import logging
import sys
import zipfile
from pathlib import Path

logging.disable(logging.CRITICAL)

try:  # androguard logs through loguru, which ignores the stdlib logging switch.
    from loguru import logger as _loguru_logger

    _loguru_logger.remove()
except Exception:  # pragma: no cover - loguru is optional
    pass

EXTENSION_PACKAGE = "Lcom/themuhammad/deepseekmod/extension/"
HOOKS_CLASS = EXTENSION_PACKAGE + "SdsAgentHooks;"
CONSOLE_ACTIVITY = "com.themuhammad.deepseekmod.extension.SdsAgentConsoleActivity"

EXPECTED_CALLS = [
    (
        "prompt serializer",
        "Ljy1;",
        "e",
        "(Lw94;Ljava/lang/Object;)V",
        HOOKS_CLASS + "->beforePrompt(Ljava/lang/String;)Ljava/lang/String;",
    ),
    (
        "streaming SET",
        "Lv44;",
        "l",
        "(Ljava/lang/String;Lc26;Lgv1;)V",
        HOOKS_CLASS + "->observeResponse(Ljava/lang/String;)V",
    ),
    (
        "streaming APPEND",
        "Lv44;",
        "m",
        "(Lc26;Ljava/lang/String;)V",
        HOOKS_CLASS + "->observeResponse(Ljava/lang/String;)V",
    ),
]

REQUIRED_EXTENSION_CLASSES = [
    HOOKS_CLASS,
    EXTENSION_PACKAGE + "SdsToolCallParser;",
    EXTENSION_PACKAGE + "SdsExecutionPolicy;",
    EXTENSION_PACKAGE + "SdsWorkspaceGuard;",
    EXTENSION_PACKAGE + "SdsToolCall;",
    EXTENSION_PACKAGE + "SdsToolResult;",
    EXTENSION_PACKAGE + "SdsCoreMarker;",
    EXTENSION_PACKAGE + "SdsAgentConsoleActivity;",
]


def load_dex(apk: Path):
    from androguard.core.dex import DEX

    with zipfile.ZipFile(apk) as archive:
        dex_names = sorted(
            name for name in archive.namelist() if name.endswith(".dex") and not name.endswith("/")
        )
        if not dex_names:
            raise SystemExit("patched APK contains no DEX files")
        dexes = []
        for name in dex_names:
            dexes.append((name, DEX(archive.read(name))))
    return dexes


def find_class(dexes, descriptor: str):
    for _, dex in dexes:
        klass = dex.get_class(descriptor)
        if klass is not None:
            return klass
    return None


def find_method(dexes, class_descriptor: str, name: str, signature: str):
    klass = find_class(dexes, class_descriptor)
    if klass is None:
        return None
    for method in klass.get_methods():
        if method.get_name() == name and method.get_descriptor().replace(" ", "") == signature:
            return method
    return None


def invoked_references(method) -> list[str]:
    code = method.get_code()
    if code is None:
        return []
    references = []
    for instruction in code.get_bc().get_instructions():
        output = instruction.get_output()
        if "->" in output:
            references.append(output.replace(" ", ""))
    return references


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2

    apk = Path(sys.argv[1])
    if not apk.is_file():
        raise SystemExit(f"patched APK not found: {apk}")

    failures: list[str] = []
    print(f"patched APK: {apk} ({apk.stat().st_size} bytes)")

    dexes = load_dex(apk)
    print(f"DEX files:   {', '.join(name for name, _ in dexes)}")

    print("\n[1] extension classes")
    for descriptor in REQUIRED_EXTENSION_CLASSES:
        if find_class(dexes, descriptor) is None:
            failures.append(f"missing extension class {descriptor}")
            print(f"  MISSING {descriptor}")
        else:
            print(f"  OK      {descriptor}")

    print("\n[2] hook call sites")
    for label, class_descriptor, method_name, signature, expected in EXPECTED_CALLS:
        method = find_method(dexes, class_descriptor, method_name, signature)
        if method is None:
            failures.append(f"{label}: method {class_descriptor}->{method_name}{signature} not found")
            print(f"  MISSING {label}: {class_descriptor}->{method_name}{signature}")
            continue
        references = invoked_references(method)
        if any(expected in reference for reference in references):
            print(f"  OK      {label}: {class_descriptor}->{method_name}{signature}")
        else:
            failures.append(
                f"{label}: {class_descriptor}->{method_name}{signature} does not call {expected}"
            )
            print(f"  FAILED  {label}: expected a call to {expected}")

    print("\n[3] manifest")
    from androguard.core.apk import APK

    apk_analysis = APK(str(apk))
    activities = apk_analysis.get_activities()
    for label, activity in (
        ("native Agent Console", CONSOLE_ACTIVITY),
        ("original DeepSeek launcher", "com.deepseek.chat.MainActivity"),
    ):
        if activity in activities:
            print(f"  OK      {label}: {activity}")
        else:
            failures.append(f"manifest does not declare {activity}")
            print(f"  MISSING {label}: {activity}")

    print()
    if failures:
        print("RESULT: FAIL")
        for failure in failures:
            print(f"  - {failure}")
        return 1

    print("RESULT: PASS - the patches are present in the intended DeepSeek methods.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
