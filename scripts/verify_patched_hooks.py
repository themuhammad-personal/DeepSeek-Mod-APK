def load_dex(apk: Path):
    from androguard.core.dex import DEX

    with zipfile.ZipFile(apk) as archive:
        dex_names = sorted(
            name for name in archive.namelist() if name.endswith(".dex") and not name.endswith("/")
        )
        if not dex_names:
            raise SystemExit("patched APK contains no DEX files")
        return [(name, DEX(archive.read(name))) for name in dex_names]


def find_class(dexes, descriptor: str):
    for _, dex in dexes:
        klass = dex.get_class(descriptor)
        if klass is not None:
            return klass
    return None


def find_method(dexes, class_descriptor: str, name: str, signature: str):
    klass = find_class(dexes, class_descriptor)
    if klass is None:
        return None
    for method in klass.get_methods():
        if method.get_name() == name and method.get_descriptor().replace(" ", "") == signature:
            return method
    return None


def instructions_of(method):
    code = method.get_code()
    if code is None:
        return []
    return list(code.get_bc().get_instructions())


def parse_instruction(instruction):
    """Split an androguard instruction output into its registers and its reference.

    androguard renders a call as "v1, v2, Lfoo;->bar()V" and a field access as
    "v1, v2, Lfoo;->name Ltype;". The reference keeps the class so that a field
    access and a call can be told apart by their prefix. Instructions without a
    reference, such as "move-result-object v4", still carry registers.
    """
    output = instruction.get_output().replace(" ", "")
    if "->" in output:
        head, tail = output.split("->", 1)
        parts = [item for item in head.split(",") if item]
        registers = [item for item in parts if item.startswith("v")]
        owner = parts[-1] if parts else ""
        return registers, f"{owner}->{tail}"
    registers = [item for item in output.split(",") if item.startswith("v")]
    return registers, output


def find_instruction(instructions, reference_prefix: str):
    for index, instruction in enumerate(instructions):
        _, reference = parse_instruction(instruction)
        if reference.startswith(reference_prefix):
            return index, instruction
    return -1, None


def collect_types(dexes):
    """Return the defined and the referenced type descriptors of every DEX file.

    The official DeepSeek APK references optional third-party SDK types that it does
    not bundle, so the set of undefined references is compared between the unpatched
    and the patched APK instead of being required to be empty.
    """
    defined: set[str] = set()
    referenced: set[str] = set()
    for _, dex in dexes:
        for klass in dex.get_classes():
            defined.add(klass.get_name())
            referenced.update(TYPE_DESCRIPTOR.findall(klass.get_superclassname() or ""))
            for interface in klass.get_interfaces() or []:
                referenced.update(TYPE_DESCRIPTOR.findall(interface))
            for field in klass.get_fields():
                referenced.update(TYPE_DESCRIPTOR.findall(field.get_descriptor()))
            for method in klass.get_methods():
                referenced.update(TYPE_DESCRIPTOR.findall(method.get_descriptor()))
                for instruction in instructions_of(method):
                    referenced.update(TYPE_DESCRIPTOR.findall(instruction.get_output()))
    return defined, referenced


def undefined_types(dexes):
    """Return the types that are referenced but not defined in any DEX file."""
    defined, referenced = collect_types(dexes)
    return {
        descriptor
        for descriptor in referenced
        if descriptor not in defined and not descriptor.startswith(FRAMEWORK_PREFIXES)
    }


def detect_profile(apk: Path) -> tuple[str, dict]:
    """Select the names of the inspected build from the version code of the APK.

    Every build of the app is obfuscated on its own, so the harness has to know
    which build it is looking at before it can look for the hook call sites.
    """
    try:
        from androguard.core.apk import APK

        version_code = str(APK(str(apk)).get_androidversion_code())
    except Exception as error:  # pragma: no cover - androguard is optional here
        raise SystemExit(f"the version code of {apk} could not be read: {error}")
    if version_code not in PROFILES:
        raise SystemExit(
            f"the version code {version_code} of {apk} is not inspected. "
            f"The inspected builds are: {', '.join(sorted(PROFILES))}."
        )
    return version_code, PROFILES[version_code]


def main() -> int:
    if len(sys.argv) not in (2, 3):
        print(__doc__, file=sys.stderr)
        return 2

    apk = Path(sys.argv[1])
    if not apk.is_file():
        raise SystemExit(f"patched APK not found: {apk}")

    failures: list[str] = []
    print(f"patched APK: {apk} ({apk.stat().st_size} bytes)")
    version_code, profile = detect_profile(apk)
    print(f"version code: {version_code}")

    dexes = load_dex(apk)
    print(f"DEX files:   {', '.join(name for name, _ in dexes)}")

    print("\n[1] extension classes")
    for descriptor in REQUIRED_EXTENSION_CLASSES:
        if find_class(dexes, descriptor) is None:
            failures.append(f"missing extension class {descriptor}")
            print(f"  MISSING {descriptor}")
        else:
            print(f"  OK      {descriptor}")

    print("\n[2] prompt hook")
    prompt = find_method(
        dexes,
        profile["prompt_class"],
        profile["prompt_method"],
        profile["prompt_descriptor"],
    )
    if prompt is None:
        failures.append(
            f"prompt serializer {profile['prompt_class']}->{profile['prompt_method']} was not found"
        )
        print(f"  MISSING prompt serializer {profile['prompt_class']}->{profile['prompt_method']}")
    else:
        prompt_instructions = instructions_of(prompt)
        field_index, _ = find_instruction(prompt_instructions, profile["prompt_field"])
        hook_index, _ = find_instruction(prompt_instructions, BEFORE_PROMPT)
        if field_index < 0:
            failures.append(f"prompt serializer does not read {profile['prompt_field']}")
            print(f"  MISSING prompt field read {profile['prompt_field']}")
        elif hook_index < 0:
            failures.append("prompt serializer does not call SdsAgentHooks.beforePrompt")
            print("  MISSING SdsAgentHooks.beforePrompt call")
        else:
            field_registers, _ = parse_instruction(prompt_instructions[field_index])
            hook_registers, _ = parse_instruction(prompt_instructions[hook_index])
            expected = field_registers[0] if field_registers else None
            actual = hook_registers[0] if hook_registers else None
            if expected and expected == actual:
                print(f"  OK      beforePrompt receives the prompt register {expected}")
            else:
                failures.append(
                    f"beforePrompt reads {actual} but the prompt field is read into {expected}"
                )
                print(f"  FAILED  beforePrompt reads {actual}, prompt field register is {expected}")
            following = prompt_instructions[hook_index + 1] if hook_index + 1 < len(prompt_instructions) else None
            if following is None or following.get_name() != "move-result-object":
                failures.append("the guarded prompt is not moved into a register")
                print("  FAILED  the guarded prompt is not moved into a register")
            else:
                move_registers, _ = parse_instruction(following)
                if move_registers and move_registers[0] == expected:
                    print(f"  OK      the guarded prompt is written back into {expected}")
                else:
                    failures.append("the guarded prompt is not written back into the prompt register")
                    print("  FAILED  the guarded prompt is not written back into the prompt register")

    print("\n[3] streaming SET hook")
    set_method = find_method(
        dexes,
        profile["set_class"],
        profile["set_method"],
        profile["set_descriptor"],
    )
    if set_method is None:
        failures.append(
            f"streaming SET method {profile['set_class']}->{profile['set_method']} was not found"
        )
        print(f"  MISSING streaming SET method {profile['set_class']}->{profile['set_method']}")
    else:
        set_instructions = instructions_of(set_method)
        update_index, _ = find_instruction(set_instructions, profile["content_set"])
        hook_index, _ = find_instruction(set_instructions, OBSERVE_RESPONSE)
        if update_index < 0:
            failures.append(
                f"streaming SET method does not call {profile['content_set'].rstrip('(')}"
            )
            print(f"  MISSING {profile['content_set'].rstrip('(')} update")
        elif hook_index < 0:
            failures.append("streaming SET method does not call SdsAgentHooks.observeResponse")
            print("  MISSING SdsAgentHooks.observeResponse call")
        else:
            update_registers, _ = parse_instruction(set_instructions[update_index])
            hook_registers, _ = parse_instruction(set_instructions[hook_index])
            expected = update_registers[1] if len(update_registers) > 1 else None
            actual = hook_registers[0] if hook_registers else None
            if expected and expected == actual:
                print(f"  OK      observeResponse receives the SET content register {expected}")
            else:
                failures.append(f"observeResponse reads {actual} but the SET content is in {expected}")
                print(f"  FAILED  observeResponse reads {actual}, SET content register is {expected}")
            if hook_index < update_index:
                failures.append(
                    "the observer runs before the content update, so it would not see the "
                    "value that the app stores"
                )
                print("  FAILED  the observer runs before the content update")
            else:
                print("  OK      the observer runs after the content update")

    print("\n[4] streaming APPEND hook")
    append_method = find_method(
        dexes,
        profile["append_class"],
        profile["append_method"],
        profile["append_descriptor"],
    )
    if append_method is None:
        failures.append(
            f"streaming APPEND method {profile['append_class']}->{profile['append_method']} "
            "was not found"
        )
        print(
            f"  MISSING streaming APPEND method "
            f"{profile['append_class']}->{profile['append_method']}"
        )
    else:
        append_instructions = instructions_of(append_method)
        update_index, _ = find_instruction(append_instructions, profile["content_append"])
        hook_index, _ = find_instruction(append_instructions, OBSERVE_RESPONSE)
        builder_index, _ = find_instruction(append_instructions, STRING_BUILDER_TOSTRING)
        if update_index < 0:
            failures.append(
                f"streaming APPEND method does not call {profile['content_append'].rstrip('(')}"
            )
            print(f"  MISSING {profile['content_append'].rstrip('(')} update")
        elif hook_index < 0:
            failures.append("streaming APPEND method does not call SdsAgentHooks.observeResponse")
            print("  MISSING SdsAgentHooks.observeResponse call")
        else:
            update_registers, _ = parse_instruction(append_instructions[update_index])
            hook_registers, _ = parse_instruction(append_instructions[hook_index])
            expected = update_registers[2] if len(update_registers) > 2 else None
            actual = hook_registers[0] if hook_registers else None
            if expected and expected == actual:
                print(f"  OK      observeResponse receives the accumulated content register {expected}")
            else:
                failures.append(
                    f"observeResponse reads {actual} but the accumulated content is in {expected}"
                )
                print(f"  FAILED  observeResponse reads {actual}, accumulated content register is {expected}")

            # The handback of a tool result has to happen before the update, because
            # the value that is written is the value that the chat renders.
            handoff_index, _ = find_instruction(append_instructions, OBSERVE_RESPONSE_APPEND)
            if handoff_index < 0:
                failures.append(
                    "streaming APPEND method does not call SdsAgentHooks.observeResponseAppend"
                )
                print("  MISSING SdsAgentHooks.observeResponseAppend call")
            else:
                handoff_registers, _ = parse_instruction(append_instructions[handoff_index])
                handed = handoff_registers[0] if handoff_registers else None
                if handed and expected and handed == expected:
                    print(f"  OK      observeResponseAppend reads the content register {handed}")
                else:
                    failures.append(
                        f"observeResponseAppend reads {handed} but the content is in {expected}"
                    )
                    print(f"  FAILED  observeResponseAppend reads {handed}, content register is {expected}")
                if update_index > 0 and handoff_index < update_index:
                    following = (
                        append_instructions[handoff_index + 1]
                        if handoff_index + 1 < len(append_instructions)
                        else None
                    )
                    if following is not None and following.get_name() == "move-result-object":
                        move_registers, _ = parse_instruction(following)
                        if move_registers and move_registers[0] == expected:
                            print(
                                f"  OK      the handback is written back into {expected} before the update"
                            )
                        else:
                            failures.append(
                                "the handback result is not written back into the content register"
                            )
                            print("  FAILED  the handback result is not written back")
                    else:
                        failures.append("the handback result is not moved into a register")
                        print("  FAILED  the handback result is not moved into a register")
                else:
                    failures.append(
                        "the handback has to run before the content update, otherwise the "
                        "result never reaches the chat"
                    )
                    print("  FAILED  the handback does not run before the update")

            if builder_index < 0:
                failures.append("streaming APPEND method does not build the content with a StringBuilder")
                print("  MISSING StringBuilder.toString call")
            else:
                following = (
                    append_instructions[builder_index + 1]
                    if builder_index + 1 < len(append_instructions)
                    else None
                )
                if following is not None and following.get_name() == "move-result-object":
                    move_registers, _ = parse_instruction(following)
                    if move_registers and move_registers[0] == expected:
                        print(
                            f"  OK      {expected} is the register produced by StringBuilder.toString"
                        )
                    else:
                        failures.append(
                            "the observed register is not the register produced by StringBuilder.toString"
                        )
                        print("  FAILED  the observed register is not the StringBuilder result")
                else:
                    failures.append("the StringBuilder result is not moved into a register")
                    print("  FAILED  the StringBuilder result is not moved into a register")

    print("\n[5] chat entry hook")
    on_create = find_method(dexes, "Lcom/deepseek/chat/MainActivity;", "onCreate", "(Landroid/os/Bundle;)V")
    if on_create is None:
        failures.append("the launcher Activity MainActivity.onCreate was not found")
        print("  MISSING MainActivity.onCreate")
    else:
        on_create_instructions = instructions_of(on_create)
        entry_index, _ = find_instruction(on_create_instructions, CHAT_ENTRY_HOOK)
        if entry_index < 0:
            failures.append("the launcher Activity does not call SdsChatEntry.attach")
            print("  MISSING SdsChatEntry.attach call")
        else:
            print("  OK      MainActivity.onCreate calls SdsChatEntry.attach")
            following = (
                on_create_instructions[entry_index + 1]
                if entry_index + 1 < len(on_create_instructions)
                else None
            )
            if following is not None and following.get_name() == "return-void":
                print("  OK      the entry is attached after the original onCreate body")
            else:
                failures.append("the chat entry is not attached at the end of onCreate")
                print("  FAILED  the chat entry is not attached at the end of onCreate")

    print("\n[6] manifest")
    from androguard.core.apk import APK

    apk_analysis = APK(str(apk))
    activities = apk_analysis.get_activities()
    for label, activity in (
        ("native Agent Console", CONSOLE_ACTIVITY),
        ("original DeepSeek launcher", "com.deepseek.chat.MainActivity"),
    ):
        if activity in activities:
            print(f"  OK      {label}: {activity}")
        else:
            failures.append(f"manifest does not declare {activity}")
            print(f"  MISSING {label}: {activity}")

    if len(sys.argv) == 3:
        source_apk = Path(sys.argv[2])
        print("\n[7] undefined type references")
        if not source_apk.is_file():
            failures.append(f"unpatched APK not found: {source_apk}")
            print(f"  MISSING unpatched APK: {source_apk}")
        else:
            source_undefined = undefined_types(load_dex(source_apk))
            patched_undefined = undefined_types(dexes)
            introduced = sorted(patched_undefined - source_undefined)
            print(
                f"  unpatched target: {len(source_undefined)} undefined type references"
                " (optional third-party SDK types that the official APK does not bundle)"
            )
            print(f"  patched APK:      {len(patched_undefined)} undefined type references")
            if introduced:
                for descriptor in introduced:
                    print(f"  FAILED  the patch introduced the undefined type {descriptor}")
                failures.append(
                    "the patch introduced undefined type references: " + ", ".join(introduced)
                )
            else:
                print("  OK      the patch introduced no new undefined type reference")
    elif len(sys.argv) > 3:
        print("\n[7] undefined type references")
        print("  SKIPPED only one APK was given, the comparison needs the unpatched target too")
        failures.append("too many arguments")

    print()
    if failures:
        print("RESULT: FAIL")
        for failure in failures:
            print(f"  - {failure}")
        return 1

    print("RESULT: PASS - the patches are present in the intended DeepSeek methods")
    print("        and read the intended registers.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
